#!/usr/bin/env bash
# Toggle system HTTP(S) proxy to Cookie Monster (127.0.0.1:8877).
# Tries GNOME (gsettings), then KDE/Plasma (kwriteconfig), then env file fallback.
set -euo pipefail
ACTION="${1:-on}"

set_gnome() {
  command -v gsettings >/dev/null 2>&1 || return 1
  case "$ACTION" in
    on|enable|1)
      gsettings set org.gnome.system.proxy mode manual
      gsettings set org.gnome.system.proxy.http host 127.0.0.1
      gsettings set org.gnome.system.proxy.http port 8877
      gsettings set org.gnome.system.proxy.https host 127.0.0.1
      gsettings set org.gnome.system.proxy.https port 8877
      echo "GNOME proxy → 127.0.0.1:8877"
      ;;
    off|disable|0)
      gsettings set org.gnome.system.proxy mode none
      echo "GNOME proxy disabled"
      ;;
    *) return 2 ;;
  esac
}

set_kde() {
  local kw=""
  if command -v kwriteconfig6 >/dev/null 2>&1; then
    kw=kwriteconfig6
  elif command -v kwriteconfig5 >/dev/null 2>&1; then
    kw=kwriteconfig5
  else
    return 1
  fi
  case "$ACTION" in
    on|enable|1)
      "$kw" --file kioslaverc --group "Proxy Settings" --key ProxyType 1
      "$kw" --file kioslaverc --group "Proxy Settings" --key httpProxy "http://127.0.0.1:8877"
      "$kw" --file kioslaverc --group "Proxy Settings" --key httpsProxy "http://127.0.0.1:8877"
      "$kw" --file kioslaverc --group "Proxy Settings" --key ftpProxy "http://127.0.0.1:8877"
      qdbus org.kde.kioslave /KIO/Scheduler reparseSlaveConfiguration "" 2>/dev/null || true
      qdbus6 org.kde.kioslave /KIO/Scheduler reparseSlaveConfiguration "" 2>/dev/null || true
      echo "KDE/Plasma proxy → 127.0.0.1:8877 ($kw)"
      ;;
    off|disable|0)
      "$kw" --file kioslaverc --group "Proxy Settings" --key ProxyType 0
      echo "KDE/Plasma proxy disabled"
      ;;
    *) return 2 ;;
  esac
}

set_env_file() {
  local dir="${XDG_CONFIG_HOME:-$HOME/.config}/cookie-monster"
  local file="$dir/proxy.env"
  mkdir -p "$dir"
  case "$ACTION" in
    on|enable|1)
      cat >"$file" <<'EOF'
# Generated by Cookie Monster — source from your shell profile if needed
export http_proxy=http://127.0.0.1:8877
export https_proxy=http://127.0.0.1:8877
export HTTP_PROXY=http://127.0.0.1:8877
export HTTPS_PROXY=http://127.0.0.1:8877
EOF
      echo "Wrote $file (source it or set DE proxy manually)"
      ;;
    off|disable|0)
      rm -f "$file"
      echo "Removed $file — unset http_proxy/https_proxy if exported"
      ;;
    *)
      echo "Usage: $0 [on|off]" >&2
      return 2
      ;;
  esac
}

if set_gnome; then
  exit 0
fi
if set_kde; then
  exit 0
fi
set_env_file
